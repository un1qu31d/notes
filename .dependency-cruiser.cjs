/**
 * Workspace boundaries — Specifications §3.5, README "Boundaries".
 *
 * A workspace (apps/*, packages/*) may depend on another one only over the
 * network or as a package: declared in package.json, imported by name,
 * through an entry point in the dependency's "exports".
 *
 * Run: npm run check:boundaries   (also runs in CI on every push and PR)
 *
 * @type {import('dependency-cruiser').IConfiguration}
 */
const WORKSPACE = '^(apps|packages)/([^/]+)/';

/** Allowed dependencies between workspaces. Change this in the PR that needs it, so it gets reviewed. */
const ALLOWED = {
  'apps/api': [],
  'apps/web': ['packages/api-client'],
  'packages/api-client': [],
};

module.exports = {
  forbidden: [
    {
      name: 'no-relative-escape',
      severity: 'error',
      comment:
        'A relative import may not leave its workspace (e.g. "../../api/src/..."). ' +
        'Import the other workspace as a package by its name instead.',
      from: { path: WORKSPACE },
      to: { dependencyTypes: ['local'], pathNot: '^$1/$2/' },
    },

    // forbidden-dependency: one rule per workspace, from the ALLOWED table above.
    ...Object.entries(ALLOWED).map(([workspace, allowed]) => ({
      name: 'forbidden-dependency',
      severity: 'error',
      comment:
        `${workspace} may only depend on: ${allowed.join(', ') || 'no other workspace'}. ` +
        'To allow more, update ALLOWED in .dependency-cruiser.cjs.',
      from: { path: `^${workspace}/` },
      to: {
        path: '^(apps|packages)/',
        pathNot: `^(${[workspace, ...allowed].join('|')})/`,
      },
    })),

    {
      name: 'undeclared-dependency',
      severity: 'error',
      comment:
        'Imports a package that is not listed in this workspace\'s package.json ' +
        '(it only works because another workspace installed it).',
      from: { path: WORKSPACE },
      to: {
        dependencyTypes: ['npm-no-pkg', 'npm-unknown'],
        // A package can be tagged both "declared" and "npm-no-pkg" (e.g. a peer + dev
        // dependency); only report it when it isn't declared at all.
        dependencyTypesNot: ['npm', 'npm-dev', 'npm-peer', 'npm-optional'],
      },
    },

    {
      name: 'private-entry-point',
      severity: 'error',
      comment:
        'Cannot be resolved — usually an import past a package\'s public entry points ' +
        '(e.g. "@notes/api-client/src/..." instead of "@notes/api-client" or "@notes/api-client/react"), ' +
        'or a typo in the path.',
      from: { path: WORKSPACE },
      to: { couldNotResolve: true },
    },
  ],

  options: {
    doNotFollow: { path: 'node_modules' },
    // Build output and files generated by Next.js. (node_modules is not excluded — that would hide
    // npm dependencies from the undeclared-dependency rule; doNotFollow keeps it from being scanned.)
    exclude: { path: '^(apps|packages)/[^/]+/((dist|\\.next|out|coverage)/|next-env\\.d\\.ts$)' },
    // Resolves the web app's "@/..." path alias.
    tsConfig: { fileName: require('node:path').join(__dirname, 'apps/web/tsconfig.json') },
    tsPreCompilationDeps: true, // also check type-only imports
    combinedDependencies: false, // use each workspace's own package.json
    enhancedResolveOptions: {
      exportsFields: ['exports'], // honour package "exports" (private-entry-point)
      conditionNames: ['import', 'require', 'node', 'default', 'types'],
      extensions: ['.ts', '.tsx', '.js', '.mjs', '.cjs', '.json'],
    },
    reporterOptions: {
      text: { highlightFocused: true },
    },
  },
};
